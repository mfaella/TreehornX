"""Operations on `networkx.utils.UnionFind` (a partition of elements).

An element that is not registered in a `UnionFind` is alone in its class. The functions never modify their inputs
(`uf[x]` registers `x`, so they read the root only of registered elements); they return a new `UnionFind`.

The names follow the order by facts (a class is a fact `x = y`): `join` adds the facts (the union of the classes),
`meet` keeps the common facts (two elements stay together only if they are together in every input).
`UnionFind` has no value equality: compare partitions with `equal` (or `partition`).
"""

from __future__ import annotations

from itertools import chain
from typing import Callable, Iterable, TypeVar

import networkx as nx

T = TypeVar("T")
R = TypeVar("R")

UnionFind = nx.utils.UnionFind


def root(uf: UnionFind[T], x: T) -> T:
    """The root of the class of `x` in `uf` (`x` itself when it is not registered), without registering `x`."""
    return uf[x] if x in uf.parents else x


def of(pairs: Iterable[tuple[T, T]]) -> UnionFind[T]:
    """The partition generated by the equalities `pairs`."""
    result: UnionFind[T] = UnionFind()
    for a, b in pairs:
        result.union(a, b)
    return result


def meet(*ufs: UnionFind[T]) -> UnionFind[T]:
    """The common facts: two elements are together only if they are together in every `uf`."""
    elements = chain.from_iterable(ufs)
    result: UnionFind[T] = UnionFind()
    first: dict[tuple[T, ...], T] = {}
    for x in elements:
        key = tuple(root(uf, x) for uf in ufs)
        if key in first:
            result.union(first[key], x)
        else:
            first[key] = x
            result[x]  # register x as its own singleton
    return result


def join(*ufs: UnionFind[T]) -> UnionFind[T]:
    """All the facts: the finest partition coarser than every `uf`."""
    result: UnionFind[T] = UnionFind()
    for uf in ufs:
        for s in uf.to_sets():
            result.union(*s)
    return result


def transform(uf: UnionFind[T], f: Callable[[T], R]) -> UnionFind[R]:
    """Every element renamed by `f` (injective on the elements of `uf`)."""
    result: UnionFind[R] = UnionFind()
    for s in uf.to_sets():
        result.union(*map(f, s))
    return result


def restrict(uf: UnionFind[T], keep: Iterable[T]) -> UnionFind[T]:
    """The facts of `uf` between the elements of `keep` only. The classes are cut, so two kept elements equal through
    a dropped one stay equal."""
    kept = set(keep)
    result: UnionFind[T] = UnionFind()
    for s in uf.to_sets():
        members = s & kept
        if members:
            result.union(*members)
    return result


def partition(uf: UnionFind[T]) -> frozenset[frozenset[T]]:
    """The classes with at least two elements: equal for two `UnionFind`s with the same facts."""
    return frozenset(frozenset(s) for s in uf.to_sets() if len(s) > 1)


def equal(a: UnionFind[T], b: UnionFind[T]) -> bool:
    """True when `a` and `b` have the same facts."""
    return partition(a) == partition(b)
